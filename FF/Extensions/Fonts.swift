import Foundation
import SwiftUI

enum Fonts {
   static var primaryFont: Font {
      return Font.subheadline
   }

   static var boldPrimaryFont: Font {
      return Font.headline
   }

   static var lightFont: Font {
      return Font.caption
   }

   static var buttonFont: Font {
      return Font.callout
   }

   static var titleFont: Font {
      return Font.largeTitle
   }

}
